import pytest

from app.services.topic_answer import topic_of


@pytest.mark.parametrize(
    "message, topic",
    [
        ("хөвөө", "хөвөө"),
        ("Хөвөө?", "хөвөө"),
        ("явган хүний зам", "явган хүний зам"),
        ("хөвөөний талаар мэдээлэл өгөөч", "хөвөөний"),
        ("надад хөвөөний талаар мэдээлэл өгөөч", "хөвөөний"),
        ("үзэгдэх зай гэж юу вэ?", "үзэгдэх зай"),
        ("уулзвар юу гэсэн үг вэ", "уулзвар"),
        ("хучилтын тухай", "хучилтын"),
        ("гүүр тайлбарлаач", "гүүр"),
    ],
)
def test_topic_questions(message, topic):
    assert topic_of(message) == topic


@pytest.mark.parametrize(
    "message",
    [
        "хөвөөний өргөн хэд вэ?",
        "II ангиллын замын хөдөлгөөний зурвасын өргөн хэд вэ?",
        "яагаад хөвөө хэрэгтэй вэ",
        "явган хүний зам хэдэн метр байх вэ",
        "хурдны замын хөдөлгөөний зурвасын тоо",
        "явган хүний замын хамгийн бага өргөн",
        "хөвөө заавал байх ёстой юу",
        "зам",
        "3.3",
        "",
    ],
)
def test_not_topic_questions(message):
    assert topic_of(message) is None
